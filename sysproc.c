extern struct spinlock scutlock;
extern int global_counts[30];

int
sys_fork(void)
{
  return fork();
}

int
sys_exit(void)
{
  exit();
  return 0;  // not reached
}

int
sys_wait(void)
{
  return wait();
}

int
sys_kill(void)
{
  int pid;

  if(argint(0, &pid) < 0)
    return -1;
  return kill(pid);
}

int
sys_getpid(void)
{
  return myproc()->pid;
}

int
sys_sbrk(void)
{
  int addr;
  int n;

  if(argint(0, &n) < 0)
    return -1;
  addr = myproc()->sz;
  if(growproc(n) < 0)
    return -1;
  return addr;
}

//Implemented the get sys_getcounts(void) function
int sys_getcounts(void) {
  int sys_id;
  // GLOBAL MODE: If user passes a negative ID (e.g., -SYS_fork)
  if(sys_id < 0) {
    int positive_id = -sys_id;
    if(positive_id >= 30) return -1;
    
    int val;
    acquire(&scutlock);   // Protect the global data while reading
    val = global_counts[positive_id];
    release(&scutlock);
    return val;
  }

  // LOCAL MODE: Standard tracking for the current process
  if(sys_id >= 30) return -1;
  return myproc()->syscall_counts[sys_id];
}

int
sys_sleep(void)
{
  int n;
  uint ticks0;

  if(argint(0, &n) < 0)
    return -1;
  acquire(&tickslock);
  ticks0 = ticks;
  while(ticks - ticks0 < n){
    if(myproc()->killed){
      release(&tickslock);
      return -1;
    }
    sleep(&ticks, &tickslock);
  }
  release(&tickslock);
  return 0;
}

// return how many clock tick interrupts have occurred
// since start.
int
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}
